export const dictionaries: Record<Lang, Dict> = { en, hi };

export const fill = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));

/** Pick the Hindi variant of a field when available, falling back to English. */
export function pick(row: object, base: string, lang: Lang): string {
  const r = row as Record<string, unknown>;
  return String((lang === "hi" && r[`${base}Hi`]) || r[`${base}En`] || "");
}
